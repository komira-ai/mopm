test "typescript: odd names, no routes, no reasons and no enum values" {
    var arena_state = std.heap.ArenaAllocator.init(t.allocator);
    defer arena_state.deinit();
    const enums = [_]model.Enum{
        .{ .name = "ErrorCode", .path = "ErrorCode", .doc = "", .parent = null, .file = "t.proto", .values = &.{
            .{ .name = "ERROR_CODE_UNSPECIFIED", .number = 0, .doc = "" },
            .{ .name = "ERROR_CODE_X", .number = 1, .doc = "", .json_option = "x-y", .err = .{ .status = 500, .message = "m", .hint = "h" } },
        } },
        .{ .name = "Empty", .path = "Empty", .doc = "", .parent = null, .file = "t.proto", .values = &.{.{ .name = "EMPTY_UNSPECIFIED", .number = 0, .doc = "" }} },
    };
    const messages = [_]model.Message{
        .{ .name = "U", .path = "U", .doc = "", .parent = null, .file = "t.proto", .is_union = true, .fields = &.{} },
        .{ .name = "V", .path = "V", .doc = "", .parent = null, .file = "t.proto", .is_union = true, .fields = &.{
            .{ .name = "n", .number = 1, .doc = "", .label = .single, .type = .{ .scalar = .int64 }, .oneof = "o", .rules = .{ .@"const" = "7" } },
            .{ .name = "m", .number = 2, .doc = "", .label = .single, .type = .{ .scalar = .int32 }, .oneof = "o" },
