//! The TypeScript writer of tools/api_gen.zig: `service/api/src/gen/registry-v2.ts` from the model (model.zig): an interface or
//! type alias for every message and enum (nested ones under their path without dots, `MeV2.Entry` is `MeV2Entry`), the error
//! catalogue, and the route table of service/api with `matchRoute`. The file typechecks under `strict` and `noUnusedLocals`.
//!
//! Order of the output: the top-level declarations in `api.order`, each followed by the messages, then the enums, nested in it
//! (recursively); the error catalogue; the routes. A refusal (a name that two declarations share, a wrapper without a `value`
//! field, no `ErrorCode` enum, an `ErrorCode` value without an `(error)` option) is reported by `generate` as `.bad` with a
//! message; `write` returns `error.Invalid` for it.

const std = @import("std");
const model = @import("model.zig");

const Allocator = std.mem.Allocator;

pub const Result = union(enum) { ok: []const u8, bad: []const u8 };

pub const WriteError = Allocator.Error || error{Invalid};

/// Names the file itself declares; a proto declaration of such a name would clash.
const reserved = [_][]const u8{ "ErrorEntry", "OperationId", "HttpMethod", "Route", "Operations", "RouteMatch" };

/// The text of the file, or why the model cannot be written.
pub fn generate(arena: Allocator, api: model.Api) Allocator.Error!Result {
    var g = Gen{ .arena = arena, .api = api, .out = std.ArrayList(u8).init(arena), .msg_names = &.{}, .enum_names = &.{}, .bad = null };
    g.run() catch |err| switch (err) {
        error.OutOfMemory => return error.OutOfMemory,
        error.Invalid => return .{ .bad = g.bad.? },
    };
    return .{ .ok = g.out.items };
}

/// `generate` for a caller that does not need the reason of a refusal.
pub fn write(arena: Allocator, api: model.Api) WriteError![]const u8 {
    return switch (try generate(arena, api)) {
        .ok => |text| text,
        .bad => error.Invalid,
    };
}

/// The routes' static code, written verbatim after `ROUTES`, `Operations`.
pub const static_code =
    \\export interface RouteMatch {
    \\  readonly route: Route;
    \\  readonly params: Readonly<Record<string, string>>;
    \\}
    \\
    \\/** The route of `method` whose path has these segments: among the routes of that method and segment count whose literal segments all equal, the one with the most literal segments, the first on a tie. */
    \\export function matchRoute(method: string, segments: readonly string[]): RouteMatch | undefined {
    \\  let best: Route | undefined;
    \\  let bestLiterals = -1;
    \\  for (const route of ROUTES) {
    \\    if (route.method !== method || route.segments.length !== segments.length) continue;
    \\    let literals = 0;
    \\    let matches = true;
    \\    for (let i = 0; i < segments.length; i++) {
    \\      const want = route.segments[i];
    \\      if (want.startsWith('{')) continue;
    \\      if (want !== segments[i]) {
    \\        matches = false;
    \\        break;
    \\      }
    \\      literals++;
    \\    }
    \\    if (matches && literals > bestLiterals) {
    \\      best = route;
    \\      bestLiterals = literals;
    \\    }
    \\  }
    \\  if (best === undefined) return undefined;
    \\  const params: Record<string, string> = {};
    \\  best.segments.forEach((segment, i) => {
    \\    if (segment.startsWith('{')) params[segment.slice(1, -1)] = segments[i];
    \\  });
    \\  return { route: best, params };
    \\}
    \\
;

const route_types =
    \\export type HttpMethod = 'GET' | 'PUT' | 'POST' | 'DELETE' | 'PATCH';
    \\
    \\export interface Route {
    \\  readonly operationId: OperationId;
    \\  readonly method: HttpMethod;
    \\  readonly path: string;
    \\  readonly segments: readonly string[];
    \\  readonly pathParams: readonly string[];
    \\  readonly queryParams: readonly string[];
    \\  readonly body: boolean;
    \\  readonly success: readonly number[];
    \\  readonly security: readonly string[];
    \\}
    \\
;

const Gen = struct {
    arena: Allocator,
    api: model.Api,
    out: std.ArrayList(u8),
    msg_names: []const []const u8,
    enum_names: []const []const u8,
    bad: ?[]const u8,

    const Error = error{ OutOfMemory, Invalid };

    fn fail(g: *Gen, comptime fmt: []const u8, args: anytype) Error {
        g.bad = try std.fmt.allocPrint(g.arena, fmt, args);
        return error.Invalid;
    }

    fn run(g: *Gen) Error!void {
        try g.assignNames();
        const w = g.out.writer();
        try w.print("// Generated by tools/api_gen.zig from spec/api/mopm/registry/v2/*.proto; do not edit, run 'zig build gen-api'.\n", .{});
        try w.print("// sources-sha256: {s}\n", .{g.api.sources_sha256});
        for (g.api.order) |d| switch (d) {
            .message => |i| try g.emitMessageTree(i),
            .enumeration => |i| try g.emitEnum(i),
        };
        try g.emitErrors();
        try g.emitRoutes();
    }

    // Names.

    fn assignNames(g: *Gen) Error!void {
        const msgs = try g.arena.alloc([]const u8, g.api.messages.len);
        const enums = try g.arena.alloc([]const u8, g.api.enums.len);
        var seen = std.StringHashMap([]const u8).init(g.arena);
        for (reserved) |r| try seen.put(r, "the generated file");
        for (g.api.messages, 0..) |m, i| {
            msgs[i] = try flatten(g.arena, m.path);
            try g.claim(&seen, msgs[i], m.path);
        }
        for (g.api.enums, 0..) |e, i| {
            enums[i] = try flatten(g.arena, e.path);
            try g.claim(&seen, enums[i], e.path);
        }
        g.msg_names = msgs;
        g.enum_names = enums;
    }

    fn claim(g: *Gen, seen: *std.StringHashMap([]const u8), name: []const u8, path: []const u8) Error!void {
        if (seen.get(name)) |other| return g.fail("'{s}' and '{s}' are both the TypeScript name '{s}'", .{ other, path, name });
        try seen.put(name, path);
    }

    fn flatten(arena: Allocator, path: []const u8) Allocator.Error![]const u8 {
        const out = try arena.alloc(u8, std.mem.replacementSize(u8, path, ".", ""));
        _ = std.mem.replace(u8, path, ".", "", out);
        return out;
    }

    // Types.

    fn baseType(g: *Gen, ty: model.Type) []const u8 {
        return switch (ty) {
            .scalar => |s| switch (s) {
                .string => "string",
                .bool => "boolean",
                else => "number",
            },
            .message => |i| g.msg_names[i],
            .enumeration => |i| g.enum_names[i],
            .empty => "undefined",
        };
    }

    /// The TypeScript type of a field's value: a map is a `Record`, a repeated field an array. Without `| null`.
    fn fieldType(g: *Gen, f: model.Field) Allocator.Error![]const u8 {
        const base = g.baseType(f.type);
        if (f.map) return std.fmt.allocPrint(g.arena, "Record<string, {s}>", .{base});
        if (f.label == .repeated) return std.fmt.allocPrint(g.arena, "{s}[]", .{base});
        return base;
    }

    // Writing helpers.

    fn doc(g: *Gen, indent: []const u8, text: []const u8) Error!void {
        if (text.len == 0) return;
        const w = g.out.writer();
        try w.print("{s}/**\n", .{indent});
        var lines = std.mem.splitScalar(u8, text, '\n');
        while (lines.next()) |line| {
            if (line.len == 0) {
                try w.print("{s} *\n", .{indent});
                continue;
            }
            try w.print("{s} * ", .{indent});
            var rest = line;
            while (std.mem.indexOf(u8, rest, "*/")) |at| {
                try w.writeAll(rest[0..at]);
                try w.writeAll("*\\/");
                rest = rest[at + 2 ..];
            }
            try w.print("{s}\n", .{rest});
        }
        try w.print("{s} */\n", .{indent});
    }

    /// `'text'`, with `\`, `'` and line breaks escaped.
    fn single(g: *Gen, text: []const u8) Error!void {
        const w = g.out.writer();
        try w.writeByte('\'');
        for (text) |c| switch (c) {
            '\\' => try w.writeAll("\\\\"),
            '\'' => try w.writeAll("\\'"),
            '\n' => try w.writeAll("\\n"),
            '\r' => try w.writeAll("\\r"),
            else => try w.writeByte(c),
        };
        try w.writeByte('\'');
    }

    /// `"text"` as a JSON string.
    fn json(g: *Gen, text: []const u8) Error!void {
        try std.json.stringify(text, .{}, g.out.writer());
    }

    /// A property name: plain when it is an identifier, else a JSON string.
    fn key(g: *Gen, name: []const u8) Error!void {
        if (isIdent(name)) return g.out.writer().writeAll(name);
        try g.json(name);
    }

    fn singleList(g: *Gen, items: []const []const u8) Error!void {
        const w = g.out.writer();
        try w.writeByte('[');
        for (items, 0..) |s, i| {
            if (i > 0) try w.writeAll(", ");
            try g.single(s);
        }
        try w.writeByte(']');
    }

    // Declarations.

    fn emitMessageTree(g: *Gen, index: usize) Error!void {
        try g.emitMessage(index);
        for (g.api.messages, 0..) |m, i| if (m.parent == index) try g.emitMessageTree(i);
        for (g.api.enums, 0..) |e, i| if (e.parent == index) try g.emitEnum(i);
    }

    fn emitEnum(g: *Gen, index: usize) Error!void {
        const e = g.api.enums[index];
        const name = g.enum_names[index];
        const values = try model.jsonValues(g.arena, e);
        const w = g.out.writer();
        try w.writeByte('\n');
        try g.doc("", e.doc);
        try w.print("export type {s} = ", .{name});
        if (values.len == 0) try w.writeAll("never");
        for (values, 0..) |v, i| {
            if (i > 0) try w.writeAll(" | ");
            try g.single(v);
        }
        try w.writeAll(";\n\n");
        const snake = try model.upperSnake(g.arena, name);
        try w.print("export const {s}_VALUES: readonly {s}[] = ", .{ snake, name });
        try g.singleList(values);
        try w.writeAll(";\n");
    }

    fn emitMessage(g: *Gen, index: usize) Error!void {
        const m = g.api.messages[index];
        const name = g.msg_names[index];
        const w = g.out.writer();
        try w.writeByte('\n');
        if (m.wrapper) {
            const value = m.field("value") orelse return g.fail("'{s}' is a wrapper without a field 'value'", .{m.path});
            try g.doc("", if (m.doc.len > 0) m.doc else value.doc);
            try w.print("export type {s} = {s};\n", .{ name, try g.fieldType(value) });
            return;
        }
        try g.doc("", m.doc);
        if (m.is_union) {
            try w.print("export type {s} =", .{name});
            if (m.fields.len == 0) try w.writeAll(" never");
            for (m.fields, 0..) |f, i| {
                try w.writeAll(if (i == 0) " " else " | ");
                if (f.rules.@"const") |c| {
                    switch (f.type) {
                        .scalar => |s| if (s == .string) try g.single(c) else try w.writeAll(c),
                        else => try g.single(c),
                    }
                } else try w.writeAll(try g.fieldType(f));
            }
            try w.writeAll(";\n");
            return;
        }
        if (m.fields.len == 0) {
            try w.print("export interface {s} {{}}\n", .{name});
            return;
        }
        try w.print("export interface {s} {{\n", .{name});
        for (m.fields) |f| {
            try g.doc("  ", f.doc);
            try w.writeAll("  ");
            try g.key(f.name);
            try w.print("{s}: {s}{s};\n", .{
                if (f.rules.required) "" else "?",
                try g.fieldType(f),
                if (f.rules.nullable) " | null" else "",
            });
        }
        try w.writeAll("}\n");
    }

    fn emitErrors(g: *Gen) Error!void {
        const codes = g.api.errorCodes() orelse return g.fail("no enum 'ErrorCode'", .{});
        const w = g.out.writer();
        try w.writeAll(
            \\
            \\export interface ErrorEntry {
            \\  readonly status: number;
            \\  readonly message: string;
            \\  readonly hint: string;
            \\}
            \\
            \\export const ERRORS: Readonly<Record<ErrorCode, ErrorEntry>> = {
            \\
        );
        for (codes.values) |v| {
            const j = (try model.jsonValue(g.arena, codes, v)) orelse continue;
            const entry = v.err orelse return g.fail("ErrorCode value '{s}' has no (error) option", .{v.name});
            try w.writeAll("  ");
            try g.key(j);
            try w.print(": {{ status: {d}, message: ", .{entry.status});
            try g.json(entry.message);
            try w.writeAll(", hint: ");
            try g.json(entry.hint);
            try w.writeAll(" },\n");
        }
        try w.writeAll("};\n\nexport const ERROR_REASONS: Readonly<Partial<Record<ErrorCode, readonly string[]>>> = {");
        var any = false;
        for (codes.values) |v| {
            const j = (try model.jsonValue(g.arena, codes, v)) orelse continue;
            const entry = v.err orelse continue;
            if (entry.reasons.len == 0) continue;
            any = true;
            try w.writeAll("\n  ");
            try g.key(j);
            try w.writeAll(": [");
            for (entry.reasons, 0..) |r, i| {
                if (i > 0) try w.writeAll(", ");
                try g.json(r);
            }
            try w.writeAll("],");
        }
        try w.writeAll(if (any) "\n};\n" else "};\n");
    }

    fn emitRoutes(g: *Gen) Error!void {
        const w = g.out.writer();
        try w.writeAll("\nexport const BASE_PATH = ");
        try g.single(g.api.base_path);
        try w.writeAll(";\n\nexport type OperationId =");
        if (g.api.rpcs.len == 0) try w.writeAll(" never");
        for (g.api.rpcs, 0..) |rpc, i| {
            try w.writeAll(if (i == 0) " " else " | ");
            try g.single(try model.operationId(g.arena, rpc.name));
        }
        try w.writeAll(";\n\n");
        try w.writeAll(route_types);
        try w.writeAll("\nexport const ROUTES: readonly Route[] = [\n");
        for (g.api.rpcs) |rpc| try g.emitRoute(rpc);
        try w.writeAll("];\n\nexport interface Operations {\n");
        for (g.api.rpcs) |rpc| try g.emitOperation(rpc);
        try w.writeAll("}\n\n");
        try w.writeAll(static_code);
    }

    fn emitRoute(g: *Gen, rpc: model.Rpc) Error!void {
        const w = g.out.writer();
        const rel = model.relativePath(g.api, rpc);
        try w.writeAll("  { operationId: ");
        try g.single(try model.operationId(g.arena, rpc.name));
        try w.print(", method: '{s}', path: ", .{@tagName(rpc.method)});
        try g.single(rel);
        var segments = std.ArrayList([]const u8).init(g.arena);
        var it = std.mem.splitScalar(u8, rel, '/');
        while (it.next()) |s| if (s.len > 0) try segments.append(s);
        try w.writeAll(", segments: ");
        try g.singleList(segments.items);
        var names = std.ArrayList([]const u8).init(g.arena);
        for (try model.pathParams(g.arena, g.api, rpc)) |f| try names.append(f.name);
        try w.writeAll(", pathParams: ");
        try g.singleList(names.items);
        names.clearRetainingCapacity();
        for (try model.queryParams(g.arena, g.api, rpc)) |f| try names.append(f.name);
        try w.writeAll(", queryParams: ");
        try g.singleList(names.items);
        try w.print(", body: {s}, success: [", .{if (rpc.body != null) "true" else "false"});
        var first = true;
        for (rpc.responses) |r| {
            if (r.is_error) continue;
            if (!first) try w.writeAll(", ");
            first = false;
            try w.print("{d}", .{r.status});
        }
        try w.writeAll("], security: ");
        try g.singleList(rpc.security);
        try w.writeAll(" },\n");
    }

    fn emitOperation(g: *Gen, rpc: model.Rpc) Error!void {
        const w = g.out.writer();
        try w.writeAll("  ");
        try g.key(try model.operationId(g.arena, rpc.name));
        try w.writeAll(": {\n    path: {");
        const path = try model.pathParams(g.arena, g.api, rpc);
        for (path, 0..) |f, i| {
            try w.writeAll(if (i == 0) " " else "; ");
            try g.key(f.name);
            try w.print(": {s}", .{try g.fieldType(f)});
        }
        try w.writeAll(if (path.len > 0) " };\n    query: {" else "};\n    query: {");
        const query = try model.queryParams(g.arena, g.api, rpc);
        for (query, 0..) |f, i| {
            try w.writeAll(if (i == 0) " " else "; ");
            try g.key(f.name);
            try w.print("?: {s}", .{try g.fieldType(f)});
        }
        try w.writeAll(if (query.len > 0) " };\n" else "};\n");
        try w.writeAll("    body: ");
        if (rpc.body) |b| {
            const input = switch (rpc.input) {
                .message => |i| g.api.messages[i],
                else => return g.fail("rpc '{s}' has a body '{s}' but no input message", .{ rpc.name, b }),
            };
            const f = input.field(b) orelse return g.fail("rpc '{s}': the body '{s}' is not a field of its input", .{ rpc.name, b });
            try w.writeAll(try g.fieldType(f));
        } else try w.writeAll("undefined");
        try w.print(" | undefined;\n    response: {s} | undefined;\n  }};\n", .{g.baseType(rpc.output)});
    }
};

fn isIdent(name: []const u8) bool {
    if (name.len == 0) return false;
    for (name, 0..) |c, i| {
        const ok = std.ascii.isAlphabetic(c) or c == '_' or c == '$' or (i > 0 and std.ascii.isDigit(c));
        if (!ok) return false;
    }
    return true;
}

