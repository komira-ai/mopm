#!/usr/bin/env python3
"""Regenerate registry/fake/errors.zig from the error catalogue of
spec/api/openapi.yaml (the ErrorCode enum and x-mopm-errors).

    python -I registry/fake/gen_errors.py

Run it after the catalogue changes; tests/contract/replay.py fails while the
codes in errors.zig differ from the spec's. Needs PyYAML (tests/contract/requirements.txt).
"""
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "registry" / "fake" / "errors.zig"

STATUS = {
    400: "bad_request",
    401: "unauthorized",
    403: "forbidden",
    404: "not_found",
    409: "conflict",
    410: "gone",
    413: "payload_too_large",
    429: "too_many_requests",
    500: "internal_server_error",
    503: "service_unavailable",
}

TAIL = r'''
/// A template parameter: `{name}` in a message or hint.
pub const Param = struct { []const u8, []const u8 };

/// `template` with each `{key}` replaced by its value from `params`; a key
/// with no value is left as written.
pub fn fill(arena: Allocator, template: []const u8, params: []const Param) Allocator.Error![]const u8 {
    var out = std.ArrayList(u8).init(arena);
    var i: usize = 0;
    while (i < template.len) {
        if (template[i] == '{') {
            if (std.mem.indexOfScalarPos(u8, template, i, '}')) |end| {
                const key = template[i + 1 .. end];
                for (params) |p| {
                    if (std.mem.eql(u8, p[0], key)) {
                        try out.appendSlice(p[1]);
                        break;
                    }
                } else try out.appendSlice(template[i .. end + 1]);
                i = end + 1;
                continue;
            }
        }
        try out.append(template[i]);
        i += 1;
    }
    return try out.toOwnedSlice();
}

test "templates take their parameters" {
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();
    const e = entry(.version_not_found);
    try std.testing.expectEqual(std.http.Status.not_found, e.status);
    try std.testing.expectEqualStrings("'json' has no version '1.0'.", try fill(a, e.message, &.{ .{ "name", "json" }, .{ "version", "1.0" } }));
    try std.testing.expectEqualStrings("List the versions with 'mopm info {name}'.", try fill(a, e.hint, &.{}));
}
'''


def zig_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    spec = yaml.safe_load((ROOT / "spec" / "api" / "openapi.yaml").read_text(encoding="utf-8"))
    catalogue = spec["x-mopm-errors"]
    codes = spec["components"]["schemas"]["ErrorCode"]["enum"]
    if set(codes) != set(catalogue):
        raise SystemExit("ErrorCode and x-mopm-errors differ: %s" % sorted(set(codes) ^ set(catalogue)))
    lines = [
        "//! The error catalogue of spec/api/openapi.yaml (`x-mopm-errors`): each code's",
        "//! HTTP status, message template and hint template. Generated by",
        "//! registry/fake/gen_errors.py; do not edit by hand. tests/contract/replay.py",
        "//! checks every error the fake sends against the catalogue.",
        "",
        'const std = @import("std");',
        "const Allocator = std.mem.Allocator;",
        "",
        "pub const Code = enum {",
    ]
    lines += ["    %s," % c for c in codes]
    lines += [
        "};",
        "",
        "pub const Entry = struct { status: std.http.Status, message: []const u8, hint: []const u8 };",
        "",
        "pub fn entry(code: Code) Entry {",
        "    return switch (code) {",
    ]
    for c in codes:
        e = catalogue[c]
        lines.append("        .%s => .{ .status = .%s, .message = %s, .hint = %s }," % (
            c, STATUS[e["status"]], zig_string(e["message"]), zig_string(e["hint"])))
    lines += ["    };", "}"]
    OUT.write_text("\n".join(lines) + "\n" + TAIL, encoding="utf-8")
    print("wrote %s: %d codes" % (OUT.relative_to(ROOT), len(codes)))


if __name__ == "__main__":
    main()
